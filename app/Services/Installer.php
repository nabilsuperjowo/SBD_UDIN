<?php

namespace App\Services;

use App\Models\User;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Schema;
use RuntimeException;

class Installer
{
    public const TABLES = ['jadwal_lapangan', 'kategori_lapangan', 'lapangan', 'pelanggan', 'pembayaran', 'pengguna', 'reservasi'];

    public function install(): void
    {
        DB::transaction(function () {
            if (DB::getDriverName() === 'pgsql') {
                DB::select('SELECT pg_advisory_xact_lock(735701)');
            }
            $tables = $this->tables();
            if ($tables !== []) {
                if ($tables !== self::TABLES || ! Schema::hasColumn('reservasi', 'nama_snapshot')) {
                    throw new RuntimeException('Database tidak kosong atau strukturnya berbeda. Pilih database baru. Tidak ada data dihapus.');
                }
                return;
            }
            $sql = file_get_contents(database_path('sql/schema.sql'));
            if (DB::getDriverName() === 'sqlite') {
                // SQLite hanya untuk tes lokal. Produksi menggunakan PostgreSQL.
                $sql = str_replace('BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', 'INTEGER PRIMARY KEY AUTOINCREMENT', $sql);
            }
            DB::unprepared($sql);
        }, 5);
    }

    public function tables(): array
    {
        $tables = DB::getDriverName() === 'pgsql'
            ? DB::table('information_schema.tables')->where('table_schema', DB::selectOne('SELECT current_schema() AS schema')->schema)->where('table_type', 'BASE TABLE')->pluck('table_name')->all()
            : array_column(DB::select("SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%'"), 'name');
        sort($tables);
        return $tables;
    }

    public function seed(): void
    {
        DB::transaction(function () {
            $this->adminAccount();
            foreach (['FUTSAL', 'BADMINTON'] as $name) {
                DB::table('kategori_lapangan')->insertOrIgnore(['nama' => $name, 'status_aktif' => true]);
            }
            foreach ([['Futsal 1', 'FUTSAL', 'Rumput Sintetis Monofilament 5 cm · 26x15 m · LED 500 lux', '150000.00'], ['Futsal 2', 'FUTSAL', 'Rumput Sintetis Premium + Shockpad', '150000.00'], ['Badminton 1', 'BADMINTON', 'Karpet Vinyl Standar BWF', '60000.00'], ['Badminton 2', 'BADMINTON', 'Karpet Vinyl Standar BWF', '60000.00']] as [$name, $category, $surface, $price]) {
                DB::table('lapangan')->insertOrIgnore(['nama' => $name, 'id_kategori' => DB::table('kategori_lapangan')->where('nama', $category)->value('id_kategori'), 'jenis' => $surface, 'harga_per_jam' => $price, 'status_aktif' => true]);
            }
        }, 5);
        $this->removeOwners();
    }

    public function adminAccount(bool $resetPassword = false): User
    {
        return DB::transaction(function () use ($resetPassword) {
            $admin = User::where('email', 'admin@admin')->lockForUpdate()->first();
            $legacy = $admin ? null : User::where('email', 'kasir@galaxy.test')->where('peran', 'KASIR')->lockForUpdate()->first();
            $account = $admin ?? $legacy;
            if (!$account) {
                return User::create(['nama'=>'Admin Kasir','email'=>'admin@admin','password_hash'=>env('DEMO_PASSWORD','admin123'),'peran'=>'KASIR','status_aktif'=>true]);
            }
            if ($legacy || $resetPassword) {
                $account->update(['nama'=>'Admin Kasir','email'=>'admin@admin','password_hash'=>env('DEMO_PASSWORD','admin123'),'peran'=>'KASIR','status_aktif'=>true,'remember_token'=>null]);
            }
            return $account;
        }, 5);
    }

    public function removeOwners(): array
    {
        return DB::transaction(function () {
            $deleted = 0;
            $archived = 0;
            $owners = DB::table('pengguna')->where('peran', 'PEMILIK')->orderBy('id_pengguna')->lockForUpdate()->get();
            foreach ($owners as $owner) {
                $used = DB::table('reservasi')->where('id_petugas', $owner->id_pengguna)->exists()
                    || DB::table('pembayaran')->where('id_petugas', $owner->id_pengguna)->exists();
                if ($used) {
                    DB::table('pengguna')->where('id_pengguna', $owner->id_pengguna)->update(['peran' => 'KASIR', 'status_aktif' => false, 'remember_token' => null]);
                    $archived++;
                } else {
                    DB::table('pengguna')->where('id_pengguna', $owner->id_pengguna)->delete();
                    $deleted++;
                }
            }
            return compact('deleted', 'archived');
        }, 5);
    }
}
