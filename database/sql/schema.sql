CREATE TABLE pengguna (
 id_pengguna BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nama VARCHAR(150) NOT NULL,
 email VARCHAR(255) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 peran VARCHAR(12) NOT NULL CHECK (peran IN ('PEMILIK','KASIR')),
 status_aktif BOOLEAN NOT NULL DEFAULT TRUE,
 remember_token VARCHAR(100),
 dibuat_pada TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX pengguna_email_unik ON pengguna(LOWER(email));

CREATE TABLE pelanggan (
 id_pelanggan BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nama VARCHAR(150) NOT NULL,
 no_whatsapp VARCHAR(20) NOT NULL UNIQUE,
 email VARCHAR(255),
 dibuat_pada TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE kategori_lapangan (
 id_kategori BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nama VARCHAR(60) NOT NULL UNIQUE,
 deskripsi TEXT,
 status_aktif BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE lapangan (
 id_lapangan BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_kategori BIGINT NOT NULL REFERENCES kategori_lapangan(id_kategori) ON DELETE RESTRICT,
 nama VARCHAR(150) NOT NULL UNIQUE,
 jenis VARCHAR(255) NOT NULL,
 harga_per_jam DECIMAL(12,2) NOT NULL CHECK (harga_per_jam >= 0 AND harga_per_jam <= 588235294.11),
 status_aktif BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE INDEX lapangan_kategori_idx ON lapangan(id_kategori);

CREATE TABLE reservasi (
 id_reservasi BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 kode VARCHAR(30) NOT NULL UNIQUE,
 request_key VARCHAR(36) NOT NULL UNIQUE,
 id_pelanggan BIGINT NOT NULL REFERENCES pelanggan(id_pelanggan) ON DELETE RESTRICT,
 id_lapangan BIGINT NOT NULL REFERENCES lapangan(id_lapangan) ON DELETE RESTRICT,
 id_petugas BIGINT NOT NULL REFERENCES pengguna(id_pengguna) ON DELETE RESTRICT,
 nama_snapshot VARCHAR(150) NOT NULL,
 whatsapp_snapshot VARCHAR(20) NOT NULL,
 email_snapshot VARCHAR(255),
 tanggal DATE NOT NULL,
 jam_mulai TIME NOT NULL,
 durasi_jam SMALLINT NOT NULL CHECK (durasi_jam BETWEEN 1 AND 17),
 tarif_snapshot DECIMAL(12,2) NOT NULL CHECK (tarif_snapshot >= 0),
 status VARCHAR(20) NOT NULL CHECK (status IN ('MENUNGGU_BAYAR','TERKONFIRMASI','SELESAI','DIBATALKAN')),
 catatan TEXT,
 dibuat_pada TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 diubah_pada TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 dihapus_pada TIMESTAMPTZ,
 CHECK (CAST(jam_mulai AS VARCHAR(8)) BETWEEN '07:00:00' AND '23:00:00'
        AND SUBSTR(CAST(jam_mulai AS VARCHAR(8)),4,5) = '00:00'
        AND CAST(SUBSTR(CAST(jam_mulai AS VARCHAR(8)),1,2) AS INTEGER) + durasi_jam <= 24)
);
CREATE INDEX reservasi_tanggal_status_idx ON reservasi(tanggal,status);
CREATE INDEX reservasi_pelanggan_idx ON reservasi(id_pelanggan);
CREATE INDEX reservasi_lapangan_idx ON reservasi(id_lapangan);
CREATE INDEX reservasi_petugas_idx ON reservasi(id_petugas);

CREATE TABLE pembayaran (
 id_pembayaran BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_reservasi BIGINT NOT NULL UNIQUE REFERENCES reservasi(id_reservasi) ON DELETE RESTRICT,
 id_petugas BIGINT NOT NULL REFERENCES pengguna(id_pengguna) ON DELETE RESTRICT,
 metode VARCHAR(12) NOT NULL CHECK (metode IN ('TUNAI','TRANSFER','QRIS')),
 jumlah_bayar DECIMAL(12,2) NOT NULL CHECK (jumlah_bayar >= 0),
 status VARCHAR(10) NOT NULL CHECK (status IN ('MENUNGGU','BERHASIL','DIBATALKAN')),
 dibayar_pada TIMESTAMPTZ,
 dibuat_pada TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CHECK (status <> 'BERHASIL' OR dibayar_pada IS NOT NULL)
);
CREATE INDEX pembayaran_petugas_idx ON pembayaran(id_petugas);

CREATE TABLE jadwal_lapangan (
 id_slot BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_lapangan BIGINT NOT NULL REFERENCES lapangan(id_lapangan) ON DELETE RESTRICT,
 tanggal DATE NOT NULL,
 jam_mulai TIME NOT NULL,
 id_reservasi BIGINT REFERENCES reservasi(id_reservasi) ON DELETE RESTRICT,
 ditutup BOOLEAN NOT NULL DEFAULT FALSE,
 CONSTRAINT slot_unik UNIQUE(id_lapangan,tanggal,jam_mulai),
 CHECK (NOT ditutup OR id_reservasi IS NULL),
 CHECK (CAST(jam_mulai AS VARCHAR(8)) BETWEEN '07:00:00' AND '23:00:00'
        AND SUBSTR(CAST(jam_mulai AS VARCHAR(8)),4,5) = '00:00')
);
CREATE INDEX jadwal_reservasi_idx ON jadwal_lapangan(id_reservasi);
CREATE INDEX jadwal_tanggal_idx ON jadwal_lapangan(tanggal);
